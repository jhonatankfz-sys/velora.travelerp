export const getStoredTours = (): Tour[] => {
  if (typeof window === 'undefined') return allTours;
  try {
    const saved = localStorage.getItem('velora_custom_tours');
    if (saved) {
      return JSON.parse(saved);
    }
  } catch (e) {
    console.error('Error loading tours from localStorage', e);
  }
  return allTours;
};

export const saveTours = (tours: Tour[]): void => {
  if (typeof window !== 'undefined') {
    localStorage.setItem('velora_custom_tours', JSON.stringify(tours));
  }
};
